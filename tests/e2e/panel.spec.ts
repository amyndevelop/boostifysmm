import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { db } from '../../src/lib/db';
const email = `demo-${randomUUID()}@example.invalid`;
const password = randomUUID() + 'Aa!';
test('registro, sesión, pedido manual, soporte y responsive', async ({ page }) => {
 const pageErrors: string[] = [];
 page.on('pageerror', error => pageErrors.push(error.message));
 await page.goto('/registro');
 await page.getByLabel('Tu nombre').fill('Cliente Demo');
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Contraseña',{exact:true}).fill(password);
 await page.getByRole('checkbox').check();
 await page.getByRole('button',{name:'Crear mi cuenta'}).click();
 await expect(page.getByRole('heading',{name:/¡Hola, Cliente/})).toBeVisible();
 const user = await db.user.findUniqueOrThrow({where:{email}});
 await db.$transaction(async tx => {
   const wallet = await tx.wallet.update({where:{userId:user.id},data:{available:{increment:'25000'}}});
   await tx.walletTransaction.create({data:{walletId:wallet.id,key:`e2e:${user.id}`,type:'DEMO_CREDIT',amount:'25000',reference:'Prueba E2E demo'}});
 });
 await page.reload();
 await page.getByRole('button',{name:'Nuevo pedido',exact:true}).first().click();
 await page.getByLabel('Servicio',{exact:true}).selectOption('demo-instagram');
 await page.getByLabel('Cantidad de unidades').fill('350');
 await page.getByLabel('Enlace del perfil o publicación').fill('https://instagram.com/boostify-demo');
 await expect(page.getByText(/\$\s*1\.750,00/).first()).toBeVisible();
 await page.getByRole('button',{name:'Revisar pedido'}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'Crear pedido',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('recibido');
 await page.getByRole('button',{name:'Ver mis pedidos'}).click();
 await expect(page.getByText('350').first()).toBeVisible();
 await page.getByRole('button',{name:/Instagram · Servicio demo/}).click();
 await expect(page.getByRole('dialog')).toContainText(/saldo reservado/i);
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Soporte',exact:true}).first().click();
 await page.getByLabel('Asunto').fill('Consulta de prueba demo');
 await page.getByLabel('Tu mensaje').fill('¿Cómo puedo seguir el estado de este pedido de demostración?');
 await page.getByRole('button',{name:'Enviar consulta'}).click();
 await expect(page.getByRole('status')).toContainText('enviada');
 await page.reload();
 await page.getByRole('button',{name:'Soporte',exact:true}).first().click();
 await expect(page.getByRole('heading',{name:'Consulta de prueba demo'})).toBeVisible();
 // Server role checks: customer must not view the administrative data.
 await page.goto('/admin');
 await expect(page.getByRole('heading',{name:'Esta página no está disponible.'})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Solicitudes de saldo'})).toHaveCount(0);
 await page.goto('/');
 await page.setViewportSize({width:390,height:844});
 await expect(page.getByRole('navigation',{name:'Navegación principal'})).toBeVisible();
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
 const cookies = await page.context().cookies();
 const session = cookies.find(c => c.name === 'boostify_session');
 expect(session?.httpOnly).toBe(true); expect(session?.sameSite).toBe('Lax');
 await page.getByRole('button',{name:'Cerrar sesión'}).click();
 await expect(page).toHaveURL(/login/);
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Contraseña',{exact:true}).fill(password);
 await page.getByRole('button',{name:'Ingresar a mi cuenta'}).click();
 await expect(page.getByRole('heading',{name:/¡Hola, Cliente/})).toBeVisible();
 expect(pageErrors).toEqual([]);
 await db.$disconnect();
});
